#!/usr/bin/env python3
"""Render non-root system units and verify the native SSH namespace contract.

Rendering never installs/enables units. The fresh bootstrap installer creates
only previously absent system artifacts. The probe never changes SSH settings,
accepts host keys, writes repositories, or starts/stops the MCP.
"""

import argparse
import os
from pathlib import Path
import pwd
import re
import shutil
import stat
import subprocess
import sys
from urllib.parse import urlsplit


# The native include is a service-only bind mount. The empty host anchor
# changes no SSH option outside this unit. It must be removed before legacy
# rollback, since the old shim deliberately rejects additional includes.
SSH_POLICY_SOURCE = Path("/etc/desktop-commander-mcp/ssh-client-policy.conf")
SSH_POLICY_TARGET = Path("/etc/ssh/ssh_config.d/99-desktop-commander-mcp.conf")
SSH_CLIENT_POLICY = """# Noninteractive SSH defaults for the MCP service only.
Host *
    BatchMode yes
    StrictHostKeyChecking yes
    UpdateHostKeys no
    ForwardAgent no
    ForwardX11 no
    ClearAllForwardings yes
"""


def render_units(user, uid, gid, home):
    # Arch workstation accounts are deliberately restricted to simple local
    # names and their canonical HOME. Never interpolate arbitrary unit syntax.
    if (not isinstance(user, str) or not re.fullmatch(r"[a-z_][a-z0-9_-]*", user)
            or type(uid) is not int or type(gid) is not int
            or not 0 < uid < 65534 or not 0 < gid < 65534
            or user == "root" or home != f"/home/{user}"):
        raise ValueError("Expected a non-root local workstation account")
    runtime = f"/run/user/{uid}"
    exe = f"{home}/.nix-profile/bin/desktop-commander-mcp-runtime"
    server = "desktop-commander-mcp-runtime.service"
    common = f"""Type=simple
User={user}
Group={gid}
WorkingDirectory={home}
Environment=HOME={home}
Environment=PATH={home}/.nix-profile/bin:{home}/.local/bin:/usr/local/bin:/usr/bin:/bin
Environment=XDG_RUNTIME_DIR={runtime}
Restart=on-failure
RestartSec=5
TimeoutStopSec=15
KillMode=control-group
RuntimeDirectoryMode=0700
UMask=0077
PrivateUsers=yes
CapabilityBoundingSet=
AmbientCapabilities=
NoNewPrivileges=yes
PrivateTmp=yes
ProtectSystem=strict
"""
    login = f"user@{uid}.service"
    install = "\n[Install]\nWantedBy=multi-user.target\n"
    return {
        server: f"""# Generated by desktop-commander-systemd.py; install only after review.
[Unit]
Description=Self-hosted Desktop Commander MCP (loopback only)
Wants=network-online.target
Requires={login}
After=network-online.target {login}

[Service]
{common}Environment=DBUS_SESSION_BUS_ADDRESS=unix:path={runtime}/bus
ReadWritePaths={home} {runtime}
BindReadOnlyPaths={SSH_POLICY_SOURCE}:{SSH_POLICY_TARGET}
RuntimeDirectory=desktop-commander-mcp
ExecStart={exe} serve
{install}""",
        "desktop-commander-mcp-tunnel.service": f"""# Generated by desktop-commander-systemd.py; install only after review.
[Unit]
Description=Authenticated Cloudflare Tunnel for Desktop Commander MCP
Wants=network-online.target
Requires={login}
Requires={server}
After=network-online.target {login} {server}
PartOf={server}
ConditionPathExists={home}/.profile_override

[Service]
{common}ProtectHome=read-only
RuntimeDirectory=desktop-commander-mcp-tunnel
ExecStart={exe} tunnel
{install}""",
    }


def install_fresh_artifacts(etc_root, account):
    """Fresh-guest only. No replacement of existing files or activation."""
    units = render_units(account.pw_name, account.pw_uid, account.pw_gid, account.pw_dir)
    etc = Path(etc_root)
    for directory in (etc, etc / "systemd", etc / "systemd/system",
                      etc / "ssh", etc / "ssh/ssh_config.d"):
        info = directory.lstat()
        if (not stat.S_ISDIR(info.st_mode) or info.st_uid != os.geteuid()
                or info.st_mode & 0o022):
            raise ValueError("Expected protected installation directories")
    policy_dir = etc / SSH_POLICY_SOURCE.parent.relative_to("/etc")
    files = {etc / "systemd/system" / name: content for name, content in units.items()}
    files[etc / SSH_POLICY_SOURCE.relative_to("/etc")] = SSH_CLIENT_POLICY
    files[etc / SSH_POLICY_TARGET.relative_to("/etc")] = ""
    if any(os.path.lexists(path) for path in (policy_dir, *files)):
        raise ValueError("Existing MCP installation; review rather than overwrite")
    # These parent directories have already been checked; exclusive creation
    # also rejects concurrent files or broken symlinks. Change no existing mode.
    old_umask = os.umask(0o022)
    created = []
    made_directory = False
    try:
        policy_dir.mkdir(mode=0o755, exist_ok=False)
        made_directory = True
        for path, content in files.items():
            with path.open("x") as output:
                created.append(path)
                output.write(content)
    except OSError:
        for path in reversed(created):
            path.unlink()
        if made_directory:
            policy_dir.rmdir()
        raise
    finally:
        os.umask(old_umask)


def minimal_identity_map(text, identity):
    if identity <= 0:
        return False
    try:
        rows = [tuple(map(int, line.split())) for line in text.splitlines()]
        return sorted(rows) == sorted([(0, 0, 1), (identity, identity, 1)])
    except (TypeError, ValueError):
        return False


def ssh_config_query(origin):
    # Query the effective native configuration only. Never connect or
    # reconstruct a Git SSH transport command from a repository URL.
    if not isinstance(origin, str) or any(c.isspace() for c in origin):
        return None
    try:
        if origin.startswith("ssh://"):
            parsed = urlsplit(origin)
            if parsed.password is not None or parsed.query or parsed.fragment or not parsed.path.strip("/"):
                return None
            user, host, port = parsed.username, parsed.hostname, parsed.port
        else:
            match = re.fullmatch(r"([^@:/]+)@([^:/]+|\[[0-9A-Fa-f:]+\]):(.+)", origin)
            if not match:
                return None
            user, host, _ = match.groups()
            host = host.strip("[]")
            port = None
        if (not user or not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.-]*", user)
                or not host or not re.fullmatch(r"[A-Za-z0-9:][A-Za-z0-9.:%_-]*", host)
                or (port is not None and not 1 <= port <= 65535)):
            return None
        return ["ssh", "-G", *(["-p", str(port)] if port is not None else []), f"{user}@{host}"]
    except ValueError:
        return None


def strict_ssh_policy(text):
    expected = {
        "batchmode": {"yes", "true"},
        "stricthostkeychecking": {"yes", "true"},
        "updatehostkeys": {"no", "false"},
        "forwardagent": {"no", "false"},
        "forwardx11": {"no", "false"},
        "clearallforwardings": {"yes", "true"},
    }
    seen = set()
    for line in text.splitlines():
        fields = line.lower().split()
        if fields and fields[0] in expected:
            key = fields[0]
            if key in seen or len(fields) != 2 or fields[1] not in expected[key]:
                return False
            seen.add(key)
    return seen == expected.keys()


def probe_git(repo):
    if any(name in os.environ for name in ("GIT_SSH_COMMAND", "GIT_SSH")):
        return "SSH_OVERRIDE_PRESENT"
    def git(*args):
        return subprocess.run(
            ["git", "-C", str(repo), *args], stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=30,
        )
    try:
        if git("config", "--get", "core.sshCommand").returncode != 1:
            return "SSH_OVERRIDE_OR_CONFIG_ERROR"
        origin = git("remote", "get-url", "origin")
        query = ssh_config_query(origin.stdout.strip()) if origin.returncode == 0 else None
        if query is None:
            return "SSH_ORIGIN_REQUIRED"
        policy = subprocess.run(
            query, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, timeout=15, cwd=repo,
        )
        if policy.returncode or not strict_ssh_policy(policy.stdout):
            return "SSH_POLICY_UNVERIFIED"
        result = git("ls-remote", "origin", "HEAD")
        if result.returncode:
            if "Bad owner or permissions" in result.stderr:
                return "SSH_OWNERSHIP_ERROR"
            if "Host key verification failed" in result.stderr:
                return "SSH_HOST_KEY_UNVERIFIED"
            return "GIT_REMOTE_READ_FAILED"
        return "PASS" if re.fullmatch(r"[0-9a-f]{40}\tHEAD\n?", result.stdout) else "HEAD_UNVERIFIED"
    except (OSError, subprocess.TimeoutExpired):
        return "GIT_EXECUTION_FAILED"


def verify_namespace():
    uid, gid = os.getuid(), os.getgid()
    if uid == 0 or uid != os.geteuid() or gid != os.getegid():
        raise ValueError("Expected an unprivileged service identity")
    proc = Path("/proc/self")
    if not (minimal_identity_map((proc / "uid_map").read_text(), uid)
            and minimal_identity_map((proc / "gid_map").read_text(), gid)):
        raise ValueError("Expected minimal root+service identity maps")
    status = dict(line.split(":", 1) for line in (proc / "status").read_text().splitlines() if ":" in line)
    if status.get("NoNewPrivs", "").strip() != "1" or any(
        int(status.get(name, "1").strip(), 16) for name in
        ("CapInh", "CapPrm", "CapEff", "CapBnd", "CapAmb")
    ):
        raise ValueError("Expected NoNewPrivileges and empty capability sets")
    include = Path("/etc/ssh/ssh_config.d/20-systemd-ssh-proxy.conf").stat()
    if include.st_uid != 0 or include.st_mode & 0o022:
        raise ValueError("SSH include is not recognized as protected and root-owned")
    # Verify the exact reviewed policy is mounted read-only, not merely an
    # empty anchor or an unrelated user-writable file.
    for path in (SSH_POLICY_SOURCE, SSH_POLICY_TARGET):
        st = path.stat()
        if st.st_uid != 0 or st.st_mode & 0o022 or path.is_symlink():
            raise ValueError("Expected root-owned protected SSH policy")
    if (not SSH_POLICY_SOURCE.samefile(SSH_POLICY_TARGET)
            or SSH_POLICY_TARGET.read_text() != SSH_CLIENT_POLICY
            or not os.statvfs(SSH_POLICY_TARGET).f_flag & os.ST_RDONLY):
        raise ValueError("Expected exact service-only read-only SSH policy")
    for path in ("/etc", "/usr", "/nix/store"):
        if not os.statvfs(path).f_flag & os.ST_RDONLY:
            raise ValueError("Expected read-only system mounts")
    home = Path.home()
    runtime = Path(f"/run/user/{uid}")
    if os.environ.get("XDG_RUNTIME_DIR") != str(runtime) or runtime.stat().st_uid != uid:
        raise ValueError("Expected the user's runtime directory")
    for path in (home, runtime):
        if path.stat().st_uid != uid or os.statvfs(path).f_flag & os.ST_RDONLY or not os.access(path, os.W_OK):
            raise ValueError("Expected writable user HOME and session runtime")
    if not shutil.which("ssh") or not os.path.samefile(shutil.which("ssh"), "/usr/bin/ssh"):
        raise ValueError("Expected native Arch OpenSSH through PATH")



def admin_probe_command(account, repos, script):
    units = render_units(account.pw_name, account.pw_uid, account.pw_gid, account.pw_dir)
    service = units["desktop-commander-mcp-runtime.service"].split("[Service]\n", 1)[1].split("\n[Install]", 1)[0]
    # Reuse the exact production sandbox/identity settings. The transient
    # probe never starts the server, binds a port or touches its runtime dir.
    properties = {
        "User", "Group", "WorkingDirectory", "PrivateUsers", "CapabilityBoundingSet",
        "AmbientCapabilities", "NoNewPrivileges", "PrivateTmp", "ProtectSystem",
        "ReadWritePaths", "BindReadOnlyPaths", "UMask",
    }
    command = ["sudo", "systemd-run", "--wait", "--pipe", "--collect"]
    for line in service.splitlines():
        key, sep, value = line.partition("=")
        if key in properties:
            command.append("--property=" + line)
        elif key == "Environment" and sep:
            command.append("--setenv=" + value)
    return command + ["/usr/bin/python3", str(script), "probe", *(str(repo) for repo in repos)]


def main():
    os.umask(0o077)
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    render = sub.add_parser("render", help="Generate reviewed unit files in a new private directory")
    render.add_argument("directory", type=Path)
    fresh = sub.add_parser("install-fresh", help="Root-only fresh-guest bootstrap: install absent system artifacts, no activation")
    fresh.add_argument("account")
    probe = sub.add_parser("probe", help="Read-only native namespace and SSH test; run inside the candidate unit")
    probe.add_argument("repos", type=Path, nargs="+")
    admin = sub.add_parser("admin-probe", help="Operator-only: run the read-only probe in a temporary system unit")
    admin.add_argument("repos", type=Path, nargs="+")
    args = parser.parse_args()
    if args.action == "render":
        account = pwd.getpwuid(os.getuid())
        units = render_units(account.pw_name, account.pw_uid, account.pw_gid, account.pw_dir)
        args.directory.mkdir(mode=0o700, exist_ok=False)
        for name, text in units.items():
            with (args.directory / name).open("x") as output:
                output.write(text)
        with (args.directory / SSH_POLICY_SOURCE.name).open("x") as output:
            output.write(SSH_CLIENT_POLICY)
        # This empty host include is only a mount point. The policy remains
        # invisible to normal XRDP/SSH sessions and the Cloudflare tunnel.
        (args.directory / "ssh-include-anchor.conf").touch(mode=0o600, exist_ok=False)
        print("Generated two system units, SSH policy and empty anchor for review; no installation or activation")
        return 0
    if args.action == "install-fresh":
        if os.getuid() != 0 or os.geteuid() != 0:
            raise ValueError("Fresh guest installation requires the privileged bootstrap")
        account = pwd.getpwnam(args.account)
        # Refuse an old user-manager installation rather than start two
        # backends on the same ports. Migration on a live host is separate.
        directory = Path(account.pw_dir) / ".config/systemd/user"
        for name in ("desktop-commander-mcp-runtime.service", "desktop-commander-mcp-tunnel.service"):
            if any(os.path.lexists(path) for path in (directory / name, directory / "default.target.wants" / name)):
                raise ValueError("Legacy user units present; explicit cutover required")
        install_fresh_artifacts(Path("/etc"), account)
        print("Installed new system artifacts; activation belongs to the reviewed bootstrap")
        return 0
    if args.action == "admin-probe":
        account = pwd.getpwuid(os.getuid())
        repos = [repo.resolve(strict=True) for repo in args.repos]
        command = admin_probe_command(account, repos, Path(__file__).resolve())
        return subprocess.run(command, check=False).returncode
    verify_namespace()
    print("PASS: minimal root+service UID/GID maps, native SSH, exact read-only client policy, protected mounts, zero capabilities and writable session paths")
    results = [probe_git(repo) for repo in args.repos]
    for index, result in enumerate(results, 1):
        print(f"SSH checkout {index}: {result}")
    return 0 if all(result == "PASS" for result in results) else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError, RuntimeError) as exc:
        sys.exit(f"BLOCKED: {exc}")
